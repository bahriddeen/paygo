// Run ONCE to create the signing keypair for Qarz Daftari licenses:
//   node tools/license-gen/generate-keys.ts
// - Writes the PRIVATE key to tools/license-gen/keys/private.pem (gitignored).
// - Embeds the PUBLIC key into src/main/license/publicKey.ts (shipped in the app).
// Keep the private key secret and backed up — it mints all activation codes.
import { generateKeyPairSync } from 'node:crypto'
import { writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))

const { publicKey, privateKey } = generateKeyPairSync('ed25519', {
  publicKeyEncoding: { type: 'spki', format: 'pem' },
  privateKeyEncoding: { type: 'pkcs8', format: 'pem' }
})

mkdirSync(join(here, 'keys'), { recursive: true })
writeFileSync(join(here, 'keys', 'private.pem'), privateKey, { mode: 0o600 })

const out = `// AUTO-GENERATED by tools/license-gen/generate-keys.ts.
// The matching private key lives only in tools/license-gen/keys/ (gitignored).
export const LICENSE_PUBLIC_KEY = \`${publicKey.trim()}\`
`
writeFileSync(join(here, '..', '..', 'src', 'main', 'license', 'publicKey.ts'), out)

console.log('Private key -> tools/license-gen/keys/private.pem (keep secret)')
console.log('Public key  -> src/main/license/publicKey.ts (embedded in app)')
